CREATE TABLE usuarios (
    ID SERIAL PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL,
    CPF VARCHAR(14) NOT NULL UNIQUE,
    SENHA VARCHAR(255) NOT NULL
);

CREATE TABLE ocorrencias (
    ID SERIAL PRIMARY KEY,
    DATA DATE NOT NULL,
    HORA TIME NOT NULL,
    RUA VARCHAR(255),
    BAIRRO VARCHAR(255),
    CEP varchar(9),
    TIPO VARCHAR(255),
    FORMA_DE_RECEBIMENTO VARCHAR(255) 
);